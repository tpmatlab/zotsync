"""Render a `Plan` as Markdown summary, CSV and an Obsidian to-do. Pure functions."""
from __future__ import annotations

import csv
import io
from collections import Counter

from .matcher import Issue, Plan

# kind -> (heading, order). Everything in the to-do is resolved manually by the user.
SECTIONS: list[tuple[str, str]] = [
    ("conflict_year", "Year mismatch"),
    ("conflict_journal", "Journal mismatch"),
    ("conflict_authors", "Authors mismatch"),
    ("conflict_modified", "Modified mismatch"),
    ("conflict_zotero_uri", "Zotero URI mismatch"),
    ("doi_suggestion", "Suggested DOI (current link preserved)"),
    ("duplicate_notion", "Duplicate rows in Notion (not merged)"),
    ("orphan_no_doi_link", "Notion rows without a usable DOI and no Zotero match"),
    ("orphan_not_in_zotero", "Notion rows whose DOI is not in Zotero"),
    ("orphan_empty", "Completely empty Notion rows"),
    ("authors_truncated", "Authors truncated (2000-character limit)"),
    ("invalid_option", "Options omitted because of commas"),
]


def _links(i: Issue) -> str:
    parts = []
    if i.notion_url:
        parts.append(f"[Notion]({i.notion_url})")
    if i.zotero_uri:
        parts.append(f"[Zotero]({i.zotero_uri})")
    return " · ".join(parts)


def _one_line(s: str) -> str:
    return " ".join(s.split())


def render_todo(plan: Plan, date: str) -> str:
    by_kind: dict[str, list[Issue]] = {}
    for i in plan.issues:
        by_kind.setdefault(i.kind, []).append(i)

    lines = [f"# Conflicts and pending items — {date}", "",
             "Generated by the zotsync dry-run. Nothing was written to Notion; resolve manually.", ""]
    for kind, heading in SECTIONS:
        items = by_kind.get(kind, [])
        if not items:
            continue
        lines += [f"## {heading} ({len(items)})", ""]
        for i in sorted(items, key=lambda x: x.title.casefold()):
            detail = f" — {_one_line(i.detail)}" if i.detail else ""
            links = _links(i)
            lines.append(f"- [ ] **{_one_line(i.title)}**{detail}" + (f" — {links}" if links else ""))
        lines.append("")
    if len(lines) == 4:
        lines.append("Nothing pending. 🎉")
    return "\n".join(lines) + "\n"


def render_summary(plan: Plan, date: str) -> str:
    fills = Counter(k for m in plan.matched for k in m.fills)
    adds = Counter(k for m in plan.matched for k, v in m.additions.items() for _ in v)
    methods = Counter(m.method for m in plan.matched)
    orphans = Counter(k for _, k in plan.orphans)
    issues = Counter(i.kind for i in plan.issues)
    remover = sum(1 for n in plan.new if "Remover" in n.group.tags)

    out = [
        f"# Dry-run summary — {date}", "",
        f"- Zotero items: {plan.zotero_items} → {plan.zotero_groups} logical papers "
        f"({plan.zotero_merged_dois} DOIs with merged copies)",
        f"- Matched: {len(plan.matched)} (DOI: {methods['doi']}, title: {methods['title']})",
        f"- New (would be created, Read/Checked unchecked): {len(plan.new)}"
        + (f" — {remover} tagged `Remover`" if remover else ""),
        f"- Duplicates in Notion (report only): {len(plan.duplicate_rows)} cases",
        f"- Notion orphans (never deleted): {len(plan.orphans)} "
        f"(empty: {orphans['empty']}, no DOI/Drive link: {orphans['no_doi_link']}, "
        f"DOI not in Zotero: {orphans['not_in_zotero']})",
        "", "## Planned fills on matched rows (empty fields only)", "",
    ]
    out += [f"- {k}: {fills[k]}" for k in ("authors", "year", "journal", "doi_link", "zotero_uri", "modified")]
    out += ["", "## Planned option union (additions only)", ""]
    out += [f"- {k}: {adds[k]}" for k in ("category", "subcategory", "tag")]
    out += ["", "## Pending items for the to-do", ""]
    out += [f"- {h}: {issues[k]}" for k, h in SECTIONS]
    return "\n".join(out) + "\n"


def render_csv(plan: Plan) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["status", "method", "doi", "title", "notion_url", "zotero_uri", "fills", "additions"])
    for m in plan.matched:
        w.writerow(["matched", m.method, m.group.doi, m.row.title or m.group.canonical.title,
                    m.row.url, m.group.canonical.zotero_uri,
                    ";".join(sorted(m.fills)),
                    ";".join(f"{k}+{len(v)}" for k, v in sorted(m.additions.items()))])
    for n in plan.new:
        w.writerow(["new", "", n.group.doi, n.title, "", n.group.canonical.zotero_uri, "", ""])
    for method, rows, g in plan.duplicate_rows:
        for r in rows:
            w.writerow(["duplicate_notion", method, g.doi, r.title, r.url, g.canonical.zotero_uri, "", ""])
    for r, kind in plan.orphans:
        w.writerow([f"orphan_{kind}", "", "", r.title, r.url, "", "", ""])
    return buf.getvalue()
